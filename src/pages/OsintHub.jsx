// ── ToolCard — one card per tool, auto-fires on mount ────────
//
// Each card owns its own input state, loading state, and last response. The
// parent staggers auto-fire kickoff via the `kickoffDelay` prop so the page
// doesn't fire 30 requests in the same tick.
function ToolCard({ tool, kickoffDelay }) {
  const seed = useMemo(() => {
    const def = TOOL_DEFAULTS[tool.name] || {}
    const out = {}
    for (const s of tool.paramSchema || []) {
      out[s.key] = def[s.key] ?? s.placeholder ?? ''
    }
    return out
  }, [tool])

  const [inputs, setInputs] = useState(seed)
  const [loading, setLoading] = useState(false)
  const [data, setData] = useState(null)
  const [error, setError] = useState(null)
  const [lastStatus, setLastStatus] = useState(null)
  const fired = useRef(false)

  const buildUrl = (curInputs) => {
    const pathParts = (tool.paramSchema || []).filter((s) => s.source === 'path')
    const queryParts = (tool.paramSchema || []).filter((s) => s.source === 'query')
    const pathSeg = pathParts
      .map((s) => encodeURIComponent(String(curInputs[s.key] ?? '').trim()))
      .filter(Boolean)
      .join('/')
    const qs = new URLSearchParams()
    for (const s of queryParts) {
      const v = String(curInputs[s.key] ?? '').trim()
      if (v) qs.set(s.key, v)
    }
    return `/tool/${tool.name}${pathSeg ? '/' + pathSeg : ''}${qs.toString() ? '?' + qs.toString() : ''}`
  }

  const run = async (curInputs = inputs) => {
    // Validate required path params.
    const pathParts = (tool.paramSchema || []).filter((s) => s.source === 'path')
    for (const s of pathParts) {
      if (s.required && !String(curInputs[s.key] ?? '').trim()) {
        setError(`${s.label} is required`)
        setLastStatus('err')
        return
      }
    }
    setLoading(true); setError(null)
    try {
      const r = await osintGet(buildUrl(curInputs))
      setData(r?.data ?? r)
      setLastStatus('ok')
    } catch (e) {
      setError(e?.body?.error || e.message || 'failed')
      setLastStatus('err')
    } finally {
      setLoading(false)
    }
  }

  // Auto-fire once, staggered.
  useEffect(() => {
    if (fired.current) return
    fired.current = true
    const t = setTimeout(() => { run(seed) }, kickoffDelay)
    return () => clearTimeout(t)
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [])

  const setInput = (k, v) => setInputs((s) => ({ ...s, [k]: v }))

  const Viz = pickViz(tool.name)

  const badge = lastStatus === 'ok'
    ? <Tooltip title='last run passed'><CheckCircleFilled className='text-emerald-400' /></Tooltip>
    : lastStatus === 'err'
      ? <Tooltip title='last run failed'><CloseCircleFilled className='text-rose-400' /></Tooltip>
      : !tool.configured
        ? <Tooltip title={`needs ${tool.needsKey}`}><ExclamationCircleFilled className='text-amber-400' /></Tooltip>
        : <Tooltip title='queued'><span className='inline-block w-2 h-2 rounded-full bg-gray-600' /></Tooltip>

  return (
    <div className='luxe-glass rounded-xl p-3 border border-white/[0.06] bg-white/[0.02] flex flex-col'>
      {/* Title row */}
      <div className='flex items-start gap-2 mb-2'>
        <ExperimentOutlined className='text-cyan-400 mt-0.5' />
        <div className='flex-1 min-w-0'>
          <div className='flex items-center gap-2 flex-wrap'>
            <span className='text-white font-bold text-xs font-mono'>{tool.name}</span>
            {badge}
            {tool.needsKey ? <Tag color='orange' className='!m-0 !text-[9px]'>key</Tag> : <Tag color='green' className='!m-0 !text-[9px]'>free</Tag>}
          </div>
          <p className='text-gray-400 text-[11px] leading-snug mt-0.5 line-clamp-2'>{tool.description}</p>
        </div>
      </div>

      {/* Inputs — inline, compact */}
      {(tool.paramSchema || []).length > 0 && (
        <div className='grid grid-cols-1 sm:grid-cols-2 gap-1.5 mb-2'>
          {tool.paramSchema.map((f) => (
            <div key={f.key}>
              <label className='text-[9px] uppercase tracking-widest text-gray-500 font-bold'>
                {f.label}{f.required && <span className='text-rose-400'> *</span>}
              </label>
              {f.type === 'number' ? (
                <InputNumber
                  size='small'
                  className='!w-full'
                  placeholder={f.placeholder}
                  value={inputs[f.key] ?? ''}
                  onChange={(v) => setInput(f.key, v ?? '')}
                />
              ) : (
                <Input
                  size='small'
                  placeholder={f.placeholder}
                  value={inputs[f.key] ?? ''}
                  onChange={(e) => setInput(f.key, e.target.value)}
                  onPressEnter={() => run()}
                />
              )}
              <div className='text-[9px] text-gray-500 mt-0.5 leading-snug line-clamp-1' title={f.helper}>{f.helper}</div>
            </div>
          ))}
        </div>
      )}

      {/* Actions */}
      <div className='flex items-center gap-2 mb-2'>
        <Button
          variant='primary'
          size='small'
          onClick={() => run()}
          disabled={loading}
          icon={loading ? null : <PlayCircleFilled />}
        >
          {loading ? 'Running…' : 'Re-run'}
        </Button>
        {!tool.configured && (
          <span className='text-[9px] text-amber-300 ml-auto'>
            env {tool.needsKey} not set
          </span>
        )}
      </div>

      {/* Result */}
      <div className='mt-1'>
        {loading ? (
          <div className='flex items-center gap-2 py-3'>
            <LuxeLoader variant='osint' size='sm' />
            <span className='text-[11px] text-gray-500'>Contacting upstream…</span>
          </div>
        ) : error ? (
          <div className='rounded-lg border border-rose-400/20 bg-rose-500/5 p-2 text-rose-200 text-xs'>
            {error}
          </div>
        ) : data != null ? (
          <Viz data={data} />
        ) : null}
      </div>
    </div>
  )
}

// ── Tool grid (auto-rendered from BE manifest) ──────────────
function ToolGrid({ manifest, q, filter }) {
  const filtered = useMemo(() => {
    if (!manifest) return []
    const needle = q.trim().toLowerCase()
    return manifest.filter((t) => {
      if (filter === 'keyless' && t.needsKey) return false
      if (filter === 'key' && !t.needsKey) return false
      if (!needle) return true
      return t.name.toLowerCase().includes(needle) || (t.description || '').toLowerCase().includes(needle)
    })
  }, [manifest, q, filter])

  if (filtered.length === 0) {
    return <div className='luxe-glass rounded-xl p-5'><Empty description={<span className='text-gray-500'>no tools match</span>} /></div>
  }

  return (
    <div className='grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-3'>
      {filtered.map((t, idx) => (
        <ToolCard
          key={t.name}
          tool={t}
          kickoffDelay={KICKOFF_DELAY_MS + idx * STAGGER_MS}
        />
      ))}
    </div>
  )
}

