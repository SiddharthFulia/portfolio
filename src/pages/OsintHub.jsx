// ── BE URL helper ─────────────────────────────────────────────
// Not going through src/api/request.js because those helpers throw on any
// non-2xx — but individual OSINT endpoints (breach without HIBP key,
// domain without Host.io key) legitimately return 501 and we want to show
// a graceful "not configured" state instead of a red toast.
const BE_URL = import.meta.env.VITE_BE_URL || 'http://localhost:4001'

async function osintGet(path) {
  const res = await fetch(`${BE_URL}/api/osint${path}`, {
    headers: { Accept: 'application/json' },
  })
  const ct = res.headers.get('content-type') || ''
  const body = ct.includes('application/json') ? await res.json().catch(() => null) : null
  if (!res.ok) {
    const err = new Error(body?.error || `HTTP ${res.status}`)
    err.status = res.status
    err.body = body
    throw err
  }
  return body
}

// ── Live telemetry (6 widgets, polling every 30 s) ──────────
function useLiveTelemetry() {
  const [state, setState] = useState({
    eq   : { loading: true, data: null, ping: 0 },
    fires: { loading: true, data: null, ping: 0 },
    iss  : { loading: true, data: null, ping: 0 },
    astros:{ loading: true, data: null, ping: 0 },
    alerts:{ loading: true, data: null, ping: 0 },
  })
  const [countries, setCountries] = useState({ loading: true, data: null, ping: 0 })

  const load = async () => {
    const now = () => Date.now()
    const [eq, fires, iss, astros, alerts] = await Promise.allSettled([
      osintGet('/earthquakes?window=hour'),
      osintGet('/eonet?days=10&limit=200'),
      osintGet('/iss'),
      osintGet('/astros'),
      osintGet('/weather-alerts'),
    ])
    setState((s) => ({
      eq    : eq.status     === 'fulfilled' ? { loading: false, data: eq.value,     ping: now() } : { ...s.eq,     loading: false },
      fires : fires.status  === 'fulfilled' ? { loading: false, data: fires.value,  ping: now() } : { ...s.fires,  loading: false },
      iss   : iss.status    === 'fulfilled' ? { loading: false, data: iss.value,    ping: now() } : { ...s.iss,    loading: false },
      astros: astros.status === 'fulfilled' ? { loading: false, data: astros.value, ping: now() } : { ...s.astros, loading: false },
      alerts: alerts.status === 'fulfilled' ? { loading: false, data: alerts.value, ping: now() } : { ...s.alerts, loading: false },
    }))
  }

  useEffect(() => {
    load()
    const t = setInterval(load, 30_000)
    return () => clearInterval(t)
  }, [])

  useEffect(() => {
    osintGet('/countries')
      .then((data) => setCountries({ loading: false, data, ping: Date.now() }))
      .catch(() => setCountries((c) => ({ ...c, loading: false })))
  }, [])

  const lastUpdate = Math.max(state.eq.ping, state.fires.ping, state.iss.ping, state.astros.ping, state.alerts.ping)
  return { ...state, countries, lastUpdate }
}

