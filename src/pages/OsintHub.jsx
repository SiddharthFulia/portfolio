const PricingTag = ({ pricing }) => {
  const p = (pricing || 'unknown').toLowerCase()
  if (p === 'free') return <Tag color='green'>FREE</Tag>
  if (p === 'freemium' || p === 'free/freemium') return <Tag color='cyan'>FREEMIUM</Tag>
  if (p === 'paid') return <Tag color='orange'>PAID</Tag>
  return <Tag color='default'>?</Tag>
}

